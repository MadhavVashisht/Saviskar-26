export interface CampusVenue {
  id: string;
  name: string;
  shortName: string;
  buildingCode: string;
  tagline: string;
  category: "technical" | "cultural" | "sports" | "non-technical" | "general" | "starnight";
  coordinates: {
    x: number; // percentage from left (0 to 100)
    y: number; // percentage from top (0 to 100)
  };
  capacity?: string;
  description: string;
  facilities: string[];
  accentColor: string; // Tailwind color token
  glowColor: string;
  pinBadge: string;
}

export interface ScheduleEvent {
  id: string;
  slug: string;
  name: string;
  category: "technical" | "cultural" | "sports" | "non-technical";
  venueId: string;
  venueName: string;
  room?: string;
  day: 1 | 2;
  date: string; // "2026-10-28" or "2026-10-29"
  startTime: string; // "10:00 AM"
  endTime: string; // "01:00 PM"
  timeSlot: string; // "Morning", "Afternoon", "Evening", "Night"
  description: string;
  prizePool?: string;
  registrationOpen: boolean;
  featured?: boolean;
}

